const messages = { en, pt }
export type Locale = keyof typeof messages

// Accepts a locale tag or a whole Accept-Language header; falls back to English.
export function pickLocale(tag: string | null | undefined): Locale {
  return tag?.trim().toLowerCase().startsWith('pt') ? 'pt' : 'en'
}

export function translator(locale: Locale) {
  return (key: MessageKey, vars: Record<string, string | number> = {}) =>
    messages[locale][key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}

// Maps a database/auth error code onto a translatable message key.
export function errorKey(code: string | null | undefined): MessageKey {
  const key = `error_${code}`
  return key in en ? (key as MessageKey) : 'error_generic'
}
